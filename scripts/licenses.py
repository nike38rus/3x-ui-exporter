#!/usr/bin/env python3
"""Refresh notices for modules linked into the executable (run from repo root)."""
import json
import os
from pathlib import Path
import shutil
import subprocess


def main():
    decoder = json.JSONDecoder()
    modules = {}
    for system, arch in [("linux", "amd64"), ("linux", "arm64"),
                         ("darwin", "amd64"), ("darwin", "arm64")]:
        env = dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0")
        raw = subprocess.check_output(["go", "list", "-deps", "-json", "."], text=True, env=env)
        while raw.strip():
            package, end = decoder.raw_decode(raw.lstrip())
            raw = raw.lstrip()[end:]
            module = package.get("Module", {})
            if module and not module.get("Main"):
                if module.get("Replace"):
                    raise SystemExit("Resolve module replacements before generating notices")
                modules[module["Path"]] = module
    target = Path("third_party_licenses")
    target.mkdir(exist_ok=True)
    expected = set()
    index = ["# Third-party notices", "",
             "Generated by `python3 scripts/licenses.py` from the executable dependency graph.",
             "These components retain their own licenses. Their source archives are linked below.",
             "Unmodified Xray source is available under MPL-2.0 at its exact archive link.", ""]
    for name, module in sorted(modules.items()):
        directory = Path(module["Dir"])
        files = sorted(p for p in directory.iterdir() if p.is_file() and
                       p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "PATENTS", "AUTHORS", "COPYRIGHT")))
        if not files:
            raise SystemExit(f"Missing license files: {name}")
        escaped = "".join("!" + c.lower() if c.isupper() else c for c in name)
        index.extend([f"## {name} {module['Version']}", "",
                      f"[Exact source archive](https://proxy.golang.org/{escaped}/@v/{module['Version']}.zip)", ""])
        for source in files:
            filename = name.replace("/", "__") + "__" + source.name
            expected.add(filename)
            shutil.copyfile(source, target / filename)
            index.append(f"- [{source.name}](third_party_licenses/{filename})")
        index.append("")
    goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
    go_license = goroot / "LICENSE"
    if not go_license.exists():
        go_license = goroot.parent / "LICENSE"  # Homebrew
    shutil.copyfile(go_license, target / "Go-LICENSE")
    expected.add("Go-LICENSE")
    index.extend(["## Go standard library", "", "- [Go license](third_party_licenses/Go-LICENSE)", ""])
    for old in target.iterdir():
        if old.is_file() and old.name not in expected:
            old.unlink()
    Path("THIRD_PARTY_NOTICES.md").write_text("\n".join(index))


if __name__ == "__main__":
    main()
